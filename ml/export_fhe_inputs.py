"""Export one reproducible test sample and trained parameters for C++ FHE."""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import numpy as np

from ml.config import ARTIFACTS_DIR, FEATURES, PROCESSED_DIR, PROJECT_ROOT


def cpp_array(values: np.ndarray) -> str:
    return ", ".join(f"{float(value):.17g}" for value in values)


def main() -> None:
    model = joblib.load(ARTIFACTS_DIR / "model.pkl")
    data = np.load(PROCESSED_DIR / "train_test_data.npz")
    sample_index = 0
    scaled_features = data["X_test"][sample_index]
    expected_target = int(data["y_test"][sample_index])
    weights = model.coef_[0]
    bias = float(model.intercept_[0])
    plain_logit = float(np.dot(scaled_features, weights) + bias)
    plain_probability = float(1.0 / (1.0 + np.exp(-plain_logit)))

    output_dir = PROJECT_ROOT / "openfhe" / "generated"
    output_dir.mkdir(parents=True, exist_ok=True)
    header = f"""// Generated by: python -m ml.export_fhe_inputs
#pragma once

#include <array>
#include <cstddef>

namespace credit_risk {{
inline constexpr std::size_t kFeatureCount = {len(FEATURES)};
inline constexpr std::array<double, kFeatureCount> kScaledFeatures = {{{cpp_array(scaled_features)}}};
inline constexpr std::array<double, kFeatureCount> kWeights = {{{cpp_array(weights)}}};
inline constexpr double kBias = {bias:.17g};
inline constexpr double kExpectedPlainLogit = {plain_logit:.17g};
inline constexpr int kExpectedTarget = {expected_target};
}}  // namespace credit_risk
"""
    (output_dir / "model_input.h").write_text(header, encoding="utf-8")

    manifest = {
        "sample_index_in_saved_test_split": sample_index,
        "features_in_order": FEATURES,
        "scaled_features": scaled_features.tolist(),
        "weights": weights.tolist(),
        "bias": bias,
        "expected_target": expected_target,
        "plain_logit": plain_logit,
        "plain_probability_exact_sigmoid_client_side_only": plain_probability,
    }
    (output_dir / "model_input.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()

