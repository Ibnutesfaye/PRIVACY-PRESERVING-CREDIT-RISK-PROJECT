"""Select and export an FHE-friendly sigmoid polynomial from measured logits."""

from __future__ import annotations

import json

import joblib
import numpy as np
from numpy.polynomial import Chebyshev, Polynomial
from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score, roc_auc_score

from ml.config import ARTIFACTS_DIR, PROCESSED_DIR, PROJECT_ROOT, REPORTS_DIR


def sigmoid(values: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-values))


def classification_metrics(y_true: np.ndarray, scores: np.ndarray) -> dict[str, float]:
    predictions = (scores >= 0.5).astype(int)
    return {
        "accuracy": float(accuracy_score(y_true, predictions)),
        "precision": float(precision_score(y_true, predictions, zero_division=0)),
        "recall": float(recall_score(y_true, predictions, zero_division=0)),
        "f1": float(f1_score(y_true, predictions, zero_division=0)),
        "roc_auc": float(roc_auc_score(y_true, scores)),
    }


def main() -> None:
    model = joblib.load(ARTIFACTS_DIR / "model.pkl")
    data = np.load(PROCESSED_DIR / "train_test_data.npz")
    x_test, y_test = data["X_test"], data["y_test"]
    logits = model.decision_function(x_test)
    exact_scores = sigmoid(logits)

    # The observed test logits are within about [-5.51, 5.51]. A symmetric
    # interval of [-6, 6] covers every measured test logit without clipping.
    interval = (-6.0, 6.0)
    grid = np.linspace(interval[0], interval[1], 20001)
    exact_grid = sigmoid(grid)
    candidates: list[dict[str, object]] = []

    for degree in (3, 5, 7):
        fitted = Chebyshev.fit(grid, exact_grid, degree, domain=interval)
        polynomial = fitted.convert(kind=Polynomial)
        coefficients = polynomial.coef
        # Sigmoid(z) - 0.5 is odd on a symmetric interval. Remove numerical
        # fitting noise in even coefficients so the FHE circuit is smaller.
        coefficients[np.abs(coefficients) < 1e-14] = 0.0
        grid_scores = polynomial(grid)
        test_scores = polynomial(logits)
        candidates.append(
            {
                "degree": degree,
                "coefficients_ascending": coefficients.tolist(),
                "grid_max_absolute_error": float(np.max(np.abs(grid_scores - exact_grid))),
                "test_mean_absolute_probability_error": float(np.mean(np.abs(test_scores - exact_scores))),
                "test_max_absolute_probability_error": float(np.max(np.abs(test_scores - exact_scores))),
                "test_score_min": float(test_scores.min()),
                "test_score_max": float(test_scores.max()),
                "metrics": classification_metrics(y_test, test_scores),
            }
        )

    # Use the lowest-degree candidate with <= 0.02 worst-case error on the
    # complete approximation interval, limiting FHE depth while meeting a
    # declared accuracy target.
    selected = next(item for item in candidates if item["grid_max_absolute_error"] <= 0.02)
    report = {
        "method": "least-squares Chebyshev fit converted to power basis",
        "interval": list(interval),
        "observed_test_logit_min": float(logits.min()),
        "observed_test_logit_max": float(logits.max()),
        "selection_rule": "lowest degree with grid max absolute error <= 0.02",
        "exact_sigmoid_metrics": classification_metrics(y_test, exact_scores),
        "candidates": candidates,
        "selected": selected,
    }

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    generated_dir = PROJECT_ROOT / "openfhe" / "generated"
    generated_dir.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "polynomial_analysis.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    coefficients = np.asarray(selected["coefficients_ascending"], dtype=float)
    header = """// Generated by: python -m ml.polynomial
#pragma once
#include <array>
#include <cstddef>
namespace credit_risk {
"""
    header += f"inline constexpr std::size_t kPolynomialDegree = {selected['degree']};\n"
    header += f"inline constexpr std::array<double, {len(coefficients)}> kSigmoidCoefficients = {{"
    header += ", ".join(f"{value:.17g}" for value in coefficients)
    header += "};\n}  // namespace credit_risk\n"
    (generated_dir / "polynomial_config.h").write_text(header, encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
